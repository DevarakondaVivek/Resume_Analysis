import { Server } from "@modelcontextprotocol/sdk/server/index.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import {
    CallToolRequestSchema,
    ListToolsRequestSchema,
} from "@modelcontextprotocol/sdk/types.js";
import * as admin from 'firebase-admin';
import * as dotenv from 'dotenv';
import path from 'path';

// Load environment variables from .env if present
dotenv.config({ path: path.resolve(__dirname, '.env') });

// Initialize Firebase Admin safely
function initializeFirebase() {
    if (admin.apps.length > 0) return admin.apps[0]!;

    const serviceAccountKey = process.env.FIREBASE_SERVICE_ACCOUNT_KEY;
    if (!serviceAccountKey) {
        console.error("FATAL ERROR: FIREBASE_SERVICE_ACCOUNT_KEY environment variable is missing.");
        console.error("Please provide a stringified JSON of your Firebase Admin Service Account Key in the .env file.");
        process.exit(1);
    }

    try {
        const credentials = JSON.parse(serviceAccountKey);
        return admin.initializeApp({
            credential: admin.credential.cert(credentials),
        });
    } catch (error: any) {
        console.error("FATAL ERROR: Failed to parse FIREBASE_SERVICE_ACCOUNT_KEY.");
        console.error("Ensure it is a valid, single-line stringified JSON.");
        process.exit(1);
    }
}

const app = initializeFirebase();
const auth = app.auth();

// Create MCP Server Instance
const server = new Server(
    {
        name: "firebase-auth-mcp",
        version: "1.0.0",
    },
    {
        capabilities: {
            tools: {},
        },
    }
);

// Define the Tools
server.setRequestHandler(ListToolsRequestSchema, async () => {
    return {
        tools: [
            {
                name: "get-firebase-user-by-email",
                description: "Fetches a Firebase Authentication user profile by their exact email address. Requires Firebase Admin privileges.",
                inputSchema: {
                    type: "object",
                    properties: {
                        email: {
                            type: "string",
                            description: "The exact email address of the Firebase user",
                        },
                    },
                    required: ["email"],
                },
            },
            {
                name: "get-firebase-user-by-uid",
                description: "Fetches a Firebase Authentication user profile by their exact UID.",
                inputSchema: {
                    type: "object",
                    properties: {
                        uid: {
                            type: "string",
                            description: "The Firebase UID string",
                        },
                    },
                    required: ["uid"],
                },
            },
            {
                name: "verify-firebase-id-token",
                description: "Verifies a Firebase client ID token and returns the decoded user payload securely.",
                inputSchema: {
                    type: "object",
                    properties: {
                        idToken: {
                            type: "string",
                            description: "The JWT ID Token generated by the Firebase client SDK (e.g., from an active session)",
                        },
                    },
                    required: ["idToken"],
                },
            }
        ],
    };
});

// Implement Tool Logic
server.setRequestHandler(CallToolRequestSchema, async (request) => {
    const { name, arguments: args } = request.params;

    try {
        if (name === "get-firebase-user-by-email") {
            const email = String(args?.email);
            const userRecord = await auth.getUserByEmail(email);
            return {
                content: [{ type: "text", text: JSON.stringify(userRecord.toJSON(), null, 2) }],
            };
        }

        if (name === "get-firebase-user-by-uid") {
            const uid = String(args?.uid);
            const userRecord = await auth.getUser(uid);
            return {
                content: [{ type: "text", text: JSON.stringify(userRecord.toJSON(), null, 2) }],
            };
        }

        if (name === "verify-firebase-id-token") {
            const idToken = String(args?.idToken);
            const decodedToken = await auth.verifyIdToken(idToken);
            return {
                content: [{ type: "text", text: JSON.stringify(decodedToken, null, 2) }],
            };
        }

        throw new Error(`Unknown tool: ${name}`);
    } catch (error: any) {
        return {
            content: [{ type: "text", text: `Error executing tool: ${error.message}` }],
            isError: true,
        };
    }
});

// Start the Server using STDIO Transport (required for local AI clients like Cursor/Claude Desktop)
async function main() {
    const transport = new StdioServerTransport();
    await server.connect(transport);
    console.error("Firebase Auth MCP Server running on stdio"); // Logging to stderr so it doesn't pollute stdout JSON boundaries
}

main().catch((error) => {
    console.error("Server fatal error:", error);
    process.exit(1);
});
